-- Общие параметры команд
--------------------
-- Параметр time - время (в секундах) исполнения команды
-- Параметр time_delta - разница (в секундах) времени исполнения текущей команды относительно предыдущей команды
-- Параметры time и time_delta не могут быть одновременно использованы для одной команды


-- Команда phrase
------------
-- Выводит текстовое сообщение
-- Параметр msg - текст сообщения
-- Параметр timeout - сколько времени показывать сообщение (не обязателен)


-- Команда entity_event
------------------
-- Выполнить команду для объекта
-- Параметр entity - имя объекта
-- Параметр action - имя команды
-- Параметр param - строковый параметр (не обязателен)


-- Команда camera_anim
-----------------
-- Выбрать анимированную камеру и запустить ее анимацию
-- Параметр file - ИМЯ камеры


-- Команда console
-----------
-- Вызвать консольную команду
-- Параметр cmd - текст команды


-- Команды sound
-----------------
-- Проиграть 2d звук
-- Параметр file - имя SoundScript'а


-- Команда eval_script
-----------------
-- Выполнить скриптовую команду
-- Параметр cmd - текст команды


-- Команда mission_script
-----------------
-- Выполнить команду из таблици Missions
-- Параметр method - текст команды


-- Команды fadeout/fadein
--------------------
-- Fade in экрана в черный цвет или Fade out экрана из черного цвета
-- Параметр time_to_fade - время фэйда (не обязателен, по умолчанию == 1)


-- Команда flash
-----------
-- Белая вспышка на экране
-- Параметр time_to_fade - время вспышки (не обязателен, по умолчанию == 1)


